#!/usr/bin/env python3
"""Build the D375-to-D815 key translation from the two lid binaries.

    keymap.py <d375 lid> <d815 lid> <out.h>

Each lid turns a Linux key code into a key ID with a switch statement. Reading
both switch tables gives, for every D375 code, the D815 code with the same ID.
"""
import re
import struct
import subprocess
import sys

import capstone

MD = capstone.Cs(capstone.CS_ARCH_ARM, capstone.CS_MODE_ARM)


def tables(path):
    """Yield {key code: key ID} for each keyboard switch in the binary."""
    d = open(path, 'rb').read()
    heads = subprocess.run(['readelf', '-lW', path], capture_output=True, text=True).stdout
    base = int(re.search(r'LOAD\s+0x0+\s+(0x\w+)', heads).group(1), 16)
    for off in range(4, len(d) - 8, 4):
        w, prev = struct.unpack_from('<II', d, off - 4)[::-1]
        if (w & 0xfffffff0) != 0x979ff100 or (prev & 0xfff0f000) != 0xe3500000:
            continue
        n = prev & 0xff
        if n < 60:
            continue
        # "sub r3, r3, #k" before the cmp means index = code - k
        sub = struct.unpack_from('<I', d, off - 8 - 12)[0]
        bias = 0
        for back in range(8, 28, 4):
            s = struct.unpack_from('<I', d, off - back)[0]
            if (s & 0xfff00000) == 0xe2400000:
                bias = s & 0xff
                break
        m = {}
        for i in range(n + 1):
            t = struct.unpack_from('<I', d, off + 8 + i * 4)[0] - base
            if not 0 <= t < len(d) - 16:
                m = None
                break
            for ins in MD.disasm(d[t:t + 16], t):
                if ins.mnemonic == 'mov' and '#' in ins.op_str:
                    m[i + bias] = int(ins.op_str.split('#')[1], 0)
                break
        if m and len(set(m.values())) > 20:
            yield m


src = max(tables(sys.argv[1]), key=len)
dst = max(tables(sys.argv[2]), key=len)
to_code = {}
for code, kid in dst.items():
    if kid:
        to_code.setdefault(kid, code)
table = [0] * 256
miss = []
# Keys the D815 lacks: use the nearest one it has.
NEAREST = {ord('v'): ord('r')}      # second call history key
# Keys the D815 lid can name but has no code for. They go through lid as P10, and
# the shim changes the name in its message to lcs. See docs/backport-guide.md.
CARRIER = ord('J'), 'P10'
RENAME = {ord('F'): 'P11', ord('L'): 'P12'}
# The app shows five keys per side and the D375 has six. Its P6 is the top right
# row, so the D375's right column moves up by one and its left row 6 becomes P11.
MOVE = {ord('G'): ord('F'), ord('H'): ord('G'), ord('I'): ord('H'),
        ord('J'): ord('I'), ord('K'): ord('J')}
rename = {}
for code, kid in src.items():
    kid = NEAREST.get(kid, kid)
    if not kid:
        continue
    if kid in RENAME:
        table[code] = to_code[CARRIER[0]]
        rename[code] = RENAME[kid]
        continue
    kid = MOVE.get(kid, kid)
    if kid in to_code:
        table[code] = to_code[kid]
    else:
        miss.append((code, kid))
same = sum(1 for c in src if table[c] == c)
print(f'D375 keys {len(src)}, D815 keys {len(dst)}, unchanged {same}, no D815 match: {miss}')
with open(sys.argv[3], 'w') as f:
    f.write('/* Generated by tools/backport/keymap.py. 0 = no equivalent. */\n')
    f.write('static const unsigned char key_map[256] = {\n')
    for c in range(256):
        if table[c]:
            f.write(f'    [{c}] = {table[c]},\n')
    f.write('};\n')
    f.write(f'\n/* These keys reach lid as {CARRIER[1]}; the shim renames them in send(). */\n')
    f.write(f'#define KEY_CARRIER "{CARRIER[1]}"\n')
    f.write('static const char *const key_rename[256] = {\n')
    for c in sorted(rename):
        f.write(f'    [{c}] = "{rename[c]}",\n')
    f.write('};\n')
